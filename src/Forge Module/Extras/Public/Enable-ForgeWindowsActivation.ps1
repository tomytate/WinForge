function Invoke-ForgeKMSActivation {
    param($Edition, $Server)
    
    $keyMap = @{
        "Pro"          = "W269N-WFGWX-YVC9B-4J6C9-T83GX"
        "Pro N"        = "MH37W-N47XK-V7XM9-C7227-GCQG9"
        "Enterprise"   = "NPPR9-FWDCX-D2C8J-H872K-2YT43"
        "Enterprise N" = "DPH2V-TTNVB-4X9Q3-TJR4H-KHJW4"
        "Education"    = "NW6C2-QMPVW-D7KKK-3GKT6-VCFB2"
        "Education N"  = "2WH4N-8QGBV-H22JP-CT43Q-MDWWJ"
        "Home"         = "TX9XD-98N7V-6WMQ6-BX7FG-H8Q99"
    }

    $key = $null
    foreach ($k in $keyMap.Keys) {
        if ($Edition -like "*$k*") {
            $key = $keyMap[$k]
            if ($k -like "*N") { break }
        }
    }
    
    if (-not $key) { Write-Error "KMS Key not found for $Edition"; return }
    
    Write-ForgeLog -Message "Installing KMS Key: $key" -Level Info
    cscript //nologo "$env:SystemRoot\System32\slmgr.vbs" /ipk $key
    
    $kmsServers = if ($Server) { @($Server) } else { @("kms.digiboy.ir", "kms.lotro.cc", "kms8.MSGuides.com") }
    foreach ($kms in $kmsServers) {
        Write-ForgeLog -Message "Trying KMS: $kms" -Level Info
        cscript //nologo "$env:SystemRoot\System32\slmgr.vbs" /skms $kms
        cscript //nologo "$env:SystemRoot\System32\slmgr.vbs" /ato
    }
}
