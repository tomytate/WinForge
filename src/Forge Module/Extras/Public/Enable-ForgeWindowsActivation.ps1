<#
.SYNOPSIS
    Activates Windows using HWID (Permanent) or KMS.
    [EXTRAS EDITION ONLY]
.DESCRIPTION
    Activates supported Windows editions using native PowerShell logic.
    Suports HWID (Permanent Digital License) via ticket generation and KMS (180 days).
    
    HWID Logic: Generates a genuine ticket signed with Microsoft's leaked private key
    and installs it using the native 'clipup' utility.
    
.PARAMETER Method
    Activation method: "HWID" (default) or "KMS".
.PARAMETER Server
    Custom KMS server (only for KMS method).
.EXAMPLE
    Enable-ForgeWindowsActivation -Method HWID
#>
function Enable-ForgeWindowsActivation {
    [CmdletBinding(SupportsShouldProcess, ConfirmImpact = 'High')]
    [OutputType([void])]
    param(
        [ValidateSet("HWID", "KMS")]
        [string]$Method = "HWID",
        [string]$Server
    )

    if ($PSCmdlet.ShouldProcess("Windows Activation", "Activate via $Method")) {
        Write-ForgeLog -Message "Starting Windows Activation ($Method)..." -Level Warning
        
        $edition = (Get-CimInstance Win32_OperatingSystem).Caption
        Write-ForgeLog -Message "Detected Edition: $edition" -Level Info
        
        if ($Method -eq "HWID") {
            Invoke-ForgeHWIDActivation -Edition $edition
        }
        else {
            Invoke-ForgeKMSActivation -Edition $edition -Server $Server
        }
    }
}

